test('optimistic concurrency: conflict on stale baseRevision', () => {
  const s = new EditableDocumentStore();
  s.createItem({ id:'seq1', workspaceId:'ws', projectId:'p', kind:'sequence', contentLocale:'en' });
  s.createDocument({ id:'doc1', workspaceId:'ws', itemId:'seq1', kind:'sequence' });
  const json: any = { children: [], theme:'t' };
  const r1 = s.applyCommand({ documentId:'doc1', workspaceId:'ws', baseRevision:null, idempotencyKey:'k1', newJson:json, actor:'a', changeReason:'init' });
  assert.equal(r1.ok, true);
  const r2 = s.applyCommand({ documentId:'doc1', workspaceId:'ws', baseRevision:null, idempotencyKey:'k2', newJson:json, actor:'a', changeReason:'stale' });
  assert.equal(r2.ok, false);
  if(!r2.ok) assert.equal(r2.code, 'conflict_base_revision');
  const r3 = s.applyCommand({ documentId:'doc1', workspaceId:'ws', baseRevision:1, idempotencyKey:'k3', newJson:json, actor:'a', changeReason:'ok' });
  assert.equal(r3.ok, true);
});
test('idempotency + approval hash bound + invalidation on edit', () => {
  const s = new EditableDocumentStore();
  s.createItem({ id:'img1', workspaceId:'ws', projectId:'p', kind:'image', contentLocale:'en' });
  s.createDocument({ id:'doc1', workspaceId:'ws', itemId:'img1', kind:'canvas' });
  s.createVariant({ id:'var1', workspaceId:'ws', itemId:'img1', purpose:'original', locale:'en' });
  const canvas: any = { layers:[{ id:'l1', type:'text', text:'hi', z:0, visible:true, locked:false }], coordinateSpace:'canonical', units:'px', origin:'0,0' };
  const c1 = s.applyCommand({ documentId:'doc1', workspaceId:'ws', baseRevision:null, idempotencyKey:'idem1', newJson:canvas, actor:'a', changeReason:'v1' });
  assert.equal(c1.ok, true);
  if(!c1.ok) throw new Error('no');
  const c1b = s.applyCommand({ documentId:'doc1', workspaceId:'ws', baseRevision:null, idempotencyKey:'idem1', newJson:canvas, actor:'a', changeReason:'v1' });
  assert.equal(c1b.ok, true);
  if(c1b.ok) assert.equal(c1b.value.created, false);
  if(c1b.ok) assert.equal(c1b.value.revision.revision, 1);
  const hash = (c1 as any).value.revision.hash as string;
  assert.match(hash, /^[0-9a-f]{64}$/);
  const ap = s.approveVariant({ variantId:'var1', workspaceId:'ws', revision:1, hash, exportProfile:'print', actor:'a' });
  assert.equal(ap.ok, true);
  assert.equal(s.getVariant('ws','var1')!.acceptedHash, hash);
  const apBad = s.approveVariant({ variantId:'var1', workspaceId:'ws', revision:1, hash: '0'.repeat(64), exportProfile:'print', actor:'a' });
  assert.equal(apBad.ok, false);
  const canvas2: any = { layers:[{ id:'l1', type:'text', text:'hello', z:0, visible:true, locked:false }], coordinateSpace:'canonical', units:'px', origin:'0,0' };
  const c2 = s.applyCommand({ documentId:'doc1', workspaceId:'ws', baseRevision:1, idempotencyKey:'idem2', newJson:canvas2, actor:'a', changeReason:'edit' });
  assert.equal(c2.ok, true);
  assert.equal(s.getVariant('ws','var1')!.acceptedHash, null);
  assert.equal(s.getVariant('ws','var1')!.acceptedRevisionRef, null);
});
test('forbidden HTML/remote code + retention/source refs, rollback does not erase journal', () => {
  const s = new EditableDocumentStore();
  s.createItem({ id:'img2', workspaceId:'ws', projectId:'p', kind:'image', contentLocale:'en', retentionPolicyId:'retain-30d', sourceRefs:['src1'] });
  assert.equal(s.getItem('ws','img2')!.retentionPolicyId, 'retain-30d');
  assert.deepEqual(s.getItem('ws','img2')!.sourceRefs, ['src1']);
  s.createDocument({ id:'doc2', workspaceId:'ws', itemId:'img2', kind:'canvas' });
  const bad: any = { layers:[{ id:'l1', type:'text', html:'<script>alert(1)</script>', z:0, visible:true, locked:false }], coordinateSpace:'canonical', units:'px', origin:'0,0' };
  const rBad = s.applyCommand({ documentId:'doc2', workspaceId:'ws', baseRevision:null, idempotencyKey:'kbad', newJson:bad, actor:'a', changeReason:'x' });
  assert.equal(rBad.ok, false);
  if(!rBad.ok) assert.equal(rBad.code, 'forbidden_html_script');
  const good: any = { layers:[{ id:'l1', type:'text', text:'a', z:0, visible:true, locked:false }], coordinateSpace:'canonical', units:'px', origin:'0,0' };
  s.applyCommand({ documentId:'doc2', workspaceId:'ws', baseRevision:null, idempotencyKey:'k1', newJson:good, actor:'a', changeReason:'init' });
  const good2: any = { layers:[{ id:'l1', type:'text', text:'b', z:0, visible:true, locked:false }], coordinateSpace:'canonical', units:'px', origin:'0,0' };
  s.applyCommand({ documentId:'doc2', workspaceId:'ws', baseRevision:1, idempotencyKey:'k2', newJson:good2, actor:'a', changeReason:'edit2' });
  const rb = s.rollback('doc2','ws',1,'a');
  assert.equal(rb.ok, true);
  assert.equal(s.listRevisions('doc2','ws').length, 3);
  assert.equal(s.getDocument('ws','doc2')!.currentRevisionRef, 3);
});
