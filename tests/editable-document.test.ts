test('renderer capability schema and unsupported outcomes', () => {
  const caps = getCapabilities();
  assert.equal(caps.version, 'r1');
  assert.ok(caps.supportedNodeTypes.includes('text'));
  assert.ok(caps.officialSource.includes('EDITABLE_DOCUMENT_CONTRACT'));
  const g = checkDocumentGrammar('canvas', { layers:[{ id:'l1', type:'unknown', z:0, visible:true, locked:false }], coordinateSpace:'canonical', units:'px', origin:'0,0' } as any);
  assert.equal((g as any).ok, false);
  const u1 = resolveUnsupported(['text','unknown']);
  assert.equal(u1.outcome, 'blocked');
  const u2 = resolveUnsupported(['text','custom-blur']);
  assert.equal(u2.outcome, 'degraded');
  const u3 = resolveUnsupported(['text']);
  assert.deepEqual(u3.unsupported, []);
  assert.equal(typeof caps.version, 'string');
});
